param(
    [string]$OutputName = "kds-vore-roguelike",
    # Same-day rebuild counter for VERSIONINFO (itch.io remains the public version authority).
    [int]$Build = 0
)

$repo = Split-Path -Parent $PSScriptRoot
$dist = Join-Path $repo "dist"
$build = Join-Path $repo "build"
$packageDir = Join-Path $dist "kds-vore-roguelike"
$archivePath = Join-Path $dist "$OutputName.zip"
# Keep outside --workpath so PyInstaller --clean cannot delete it mid-build.
$versionFile = Join-Path $PSScriptRoot "file_version_info.generated.txt"

Push-Location $repo
Remove-Item -Recurse -Force $dist, $build -ErrorAction SilentlyContinue

# Date-stamped PE VERSIONINFO (itch.io is the release version authority; this is build metadata only).
$now = Get-Date
$verYear = $now.Year
$verMonth = $now.Month
$verDay = $now.Day
if ($Build -lt 0) {
    throw "Build must be >= 0."
}
$versionString = "$verYear.$verMonth.$verDay.$Build"
$productName = "K.D.'s Vore Roguelike"
$companyName = "K.D."
$copyright = "Copyright (c) K.D."
$internalName = "kds-vore-roguelike"
$originalFilename = "kds-vore-roguelike.exe"

# Double-quoted StringStruct values so apostrophes in the product name are safe for PyInstaller's eval.
$versionInfo = @"
# UTF-8
# Generated by scripts/build_windows_alpha.ps1 — do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=($verYear, $verMonth, $verDay, $Build),
    prodvers=($verYear, $verMonth, $verDay, $Build),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [
          StringStruct('CompanyName', "$companyName"),
          StringStruct('FileDescription', "$productName"),
          StringStruct('FileVersion', "$versionString"),
          StringStruct('InternalName', "$internalName"),
          StringStruct('LegalCopyright', "$copyright"),
          StringStruct('OriginalFilename', "$originalFilename"),
          StringStruct('ProductName', "$productName"),
          StringStruct('ProductVersion', "$versionString")
        ]
      )
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"@
Set-Content -Path $versionFile -Value $versionInfo -Encoding utf8
Write-Host "VERSIONINFO: $productName $versionString (CompanyName=$companyName)"

& .\.venv\Scripts\python.exe -m PyInstaller `
  --noconfirm `
  --clean `
  --windowed `
  --noupx `
  --name "kds-vore-roguelike" `
  --distpath $dist `
  --workpath $build `
  --version-file $versionFile `
  --add-data "data;data" `
  --add-data "images;images" `
  "src\main.py"

if ($LASTEXITCODE -ne 0) {
    throw "PyInstaller build failed."
}

if (-not (Test-Path $packageDir)) {
    throw "Expected package directory not found: $packageDir"
}

Copy-Item "data\Readme.txt" $packageDir -Force

if (Test-Path $archivePath) {
    Remove-Item $archivePath -Force
}

# Python zipfile (not Compress-Archive): forward-slash paths so itch.io / Go
# unzippers do not reject entries as "insecure file path".
$zipScript = Join-Path $PSScriptRoot "zip_release_dir.py"
& .\.venv\Scripts\python.exe $zipScript $packageDir $archivePath
if ($LASTEXITCODE -ne 0) {
    throw "Zip packaging failed."
}

$exePath = Join-Path $packageDir "kds-vore-roguelike.exe"
$vi = (Get-Item $exePath).VersionInfo
Write-Host "Built release archive: $archivePath"
Write-Host ("EXE Details: ProductName={0}; FileVersion={1}; CompanyName={2}" -f $vi.ProductName, $vi.FileVersion, $vi.CompanyName)
Pop-Location
